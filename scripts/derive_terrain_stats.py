#!/usr/bin/env python3
"""Derive terrain statistics from the Odyssey site-orbit heightmaps.

Reads the 512 x 320 float32 Copernicus DEM heightmaps already generated by
``fetch_site_terrain.py`` and adds a compact ``stats`` block to
``src/data/siteTerrain.json``.

The statistics are derived from the 40 m heightmap, not measured in the field:

  meanSlope       mean surface gradient, degrees
  p95Slope        95th percentile gradient, degrees
  maxSlope        maximum cell gradient, degrees
  flatFraction    fraction of cells below 5 degrees
  roughness       RMS residual against a 3 x 3 neighbourhood, metres
  elevRange       max - min elevation, metres

Requires: numpy.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
META_PATH = ROOT / "src" / "data" / "siteTerrain.json"
PUBLIC = ROOT / "public"


def roughness_rms(dem: np.ndarray) -> float:
    padded = np.pad(dem, 1, mode="edge")
    total = np.zeros_like(dem)
    for dy in range(3):
        for dx in range(3):
            total += padded[dy : dy + dem.shape[0], dx : dx + dem.shape[1]]
    local_mean = total / 9.0
    residual = dem - local_mean
    return float(np.sqrt(np.mean(residual * residual)))


def main() -> None:
    payload = json.loads(META_PATH.read_text())
    sites = payload["sites"]
    for site_id, meta in sites.items():
        path = PUBLIC / meta["file"].lstrip("/")
        dem = np.fromfile(path, dtype="<f4")
        expected = meta["width"] * meta["height"]
        if dem.size != expected:
            raise ValueError(f"{site_id}: {dem.size} values, expected {expected}")
        dem = dem.reshape(meta["height"], meta["width"])
        spacing = float(meta["mpp"])
        gy, gx = np.gradient(dem, spacing, spacing)
        slope = np.degrees(np.arctan(np.hypot(gx, gy)))
        stats = {
            "meanSlope": round(float(slope.mean()), 2),
            "p95Slope": round(float(np.percentile(slope, 95)), 2),
            "maxSlope": round(float(slope.max()), 2),
            "flatFraction": round(float((slope < 5.0).mean()), 4),
            "roughness": round(roughness_rms(dem), 2),
            "elevRange": round(float(dem.max() - dem.min()), 2),
        }
        meta["stats"] = stats
        print(
            f"  {site_id:16s} slope {stats['meanSlope']:5.2f} / p95 "
            f"{stats['p95Slope']:5.2f} / max {stats['maxSlope']:5.2f} deg  "
            f"flat {stats['flatFraction']*100:5.1f}%  rough {stats['roughness']:4.2f} m"
        )
    META_PATH.write_text(json.dumps(payload, indent=2) + "\n")
    print(f"\nWrote {META_PATH} ({len(sites)} sites)")


if __name__ == "__main__":
    main()
